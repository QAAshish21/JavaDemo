package day4;

public class PostiveOrNegativeNumberDemo {

	public static void main(String[] args) {

		int num = -5;

		if (num > 0) {
			System.out.println("Postive Number");
		} else if (num < 0) {
			System.out.println("Negative Number");
		} else {
			System.out.println("Zero number");
		}

	}

}
