package day11;

public class Greetings {

	// 1 . No Param (argument ) & No return

	void m1() {
		System.out.println("Hello....");
	}

	// 2 . No param (argument ) & Return value

	String m2() {
		return "Hello...How are you ?";
	}

	// 3 . Take param (argument ) & No return

	void m3(String name) {
		System.out.println("Hello... " + name);
	}

	// 4 . Take param (argument) & return

	String m4(String name) {
		return "I am Fine";
	}

}
