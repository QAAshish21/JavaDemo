package day2;

public class DataTypesDemo {

	public static void main(String[] args) {

		// Numeric Datatype

		int a = 100, b = 200;

		System.out.println("The value of a is : " + a);
		System.out.println("The value of b is : " + b);
		System.out.println("Sum of a and b is : " + (a + b));

		byte run = 125;
		System.out.println("Best score of Dhoni : " + run);

		short count = 12345;
		System.out.println("Count of clock : " + count);

		long gdp = 859632145987L;
		System.out.println("GDP of USA : " + gdp);

		// Decimal Number - float ,double

		float item_price = 15.6f;
		System.out.println(item_price);

		double dbl = 145693.45;
		System.out.println(dbl);

		char grade = 'A';
		System.out.println(grade);

		String name = "Ashish Sawarkar";
		System.out.println(name);

		// char ch ='ABC'; // Invalid
		// String s ='ABC'; // Invalid

		// String st ='A'; // Invalid

		boolean bg = true;
		System.out.println(bg);

		boolean bl = false;
		System.out.println(bl);

	}

}
